#include <stdint.h>
#include <stddef.h>
#include "latin1.h"

// Glyphs for the Latin-1 characters the German keyboard layout can type.
// Same format as the ASCII font in terminal.c: 8 rows, bit 0 = leftmost pixel. 
struct latin1_glyph {
    uint8_t ch;
    uint8_t rows[8];
};

static const struct latin1_glyph glyphs[] = {
    { 0xA7, { 0x3C,0x06,0x1C,0x32,0x1C,0x30,0x1E,0x00 } }, // section sign 
    { 0xB0, { 0x0C,0x12,0x12,0x0C,0x00,0x00,0x00,0x00 } }, // degree sign 
    { 0xB2, { 0x06,0x09,0x04,0x02,0x0F,0x00,0x00,0x00 } }, // superscript 2 
    { 0xB3, { 0x07,0x04,0x06,0x04,0x07,0x00,0x00,0x00 } }, // superscript 3 
    { 0xB4, { 0x18,0x0C,0x06,0x00,0x00,0x00,0x00,0x00 } }, // acute accent 
    { 0xB5, { 0x00,0x00,0x33,0x33,0x33,0x33,0x3E,0x03 } }, // micro sign 
    { 0xC4, { 0x33,0x00,0x0C,0x1E,0x33,0x3F,0x33,0x33 } }, // A umlaut 
    { 0xD6, { 0x33,0x00,0x1C,0x36,0x63,0x63,0x36,0x1C } }, // O umlaut 
    { 0xDC, { 0x33,0x00,0x33,0x33,0x33,0x33,0x33,0x3F } }, // U umlaut 
    { 0xDF, { 0x1E,0x33,0x33,0x1B,0x33,0x33,0x1B,0x00 } }, // sharp s 
    { 0xE4, { 0x33,0x00,0x1E,0x30,0x3E,0x33,0x6E,0x00 } }, // a umlaut 
    { 0xF6, { 0x33,0x00,0x1E,0x33,0x33,0x33,0x1E,0x00 } }, // o umlaut 
    { 0xFC, { 0x33,0x00,0x33,0x33,0x33,0x33,0x6E,0x00 } }, // u umlaut 
};

const uint8_t *latin1_glyph(uint8_t ch) {
    for (size_t i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); i++)
        if (glyphs[i].ch == ch) return glyphs[i].rows;
    return NULL;
}

// In VGA text mode the hardware font is code page 437. Most of our characters have a
// glyph there under a different code; anything else is passed through unchanged. 
uint8_t latin1_to_vga(uint8_t ch) {
    switch (ch) {
    case 0xE4: return 0x84;      // a umlaut 
    case 0xC4: return 0x8E;      // A umlaut 
    case 0xF6: return 0x94;      // o umlaut 
    case 0xD6: return 0x99;      // O umlaut 
    case 0xFC: return 0x81;      // u umlaut 
    case 0xDC: return 0x9A;      // U umlaut 
    case 0xDF: return 0xE1;      // sharp s 
    case 0xB0: return 0xF8;      // degree sign 
    case 0xB2: return 0xFD;      // superscript 2 
    case 0xB5: return 0xE6;      // micro sign 
    case 0xA7: return 0x15;      // section sign (glyph 0x15 of the VGA font) 
    case 0xB3: return '3';       // no superscript 3 in code page 437 
    case 0xB4: return '\'';      // no acute accent either 
    default:   return ch;
    }
}